  const DICTS = { en, he };
  let lang = "en";

  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
  }

  function raw(key) {
    const s = DICTS[lang][key];
    return s != null ? s : en[key] != null ? en[key] : key;
  }

  function t(key, vars) {
    const s = esc(raw(key));
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? esc(vars[k]) : m)) : s;
  }

  // Plain text (unescaped), for recaps that are shared outside the page.
  function fmt(key, vars) {
    const s = raw(key);
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
  }

  function setLang(next) {
    lang = DICTS[next] ? next : "en";
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
  }

  CT.I18n = { t, raw, fmt, setLang, dir: () => (lang === "he" ? "rtl" : "ltr"), DICTS };
